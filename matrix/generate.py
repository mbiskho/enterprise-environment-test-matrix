"""environments.yaml → .github/workflows/matrix.yml. Run after editing the matrix."""

from __future__ import annotations

from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]

SERVICES = {
    "squid": {"image": "ubuntu/squid:6.6-24.04_beta", "ports": ["3128:3128"]},
    "squid-tls-intercept": {"image": "ubuntu/squid:6.6-24.04_beta", "ports": ["3128:3128"]},
    "keycloak": {"image": "quay.io/keycloak/keycloak:26.0", "ports": ["8081:8080"],
                 "env": {"KC_BOOTSTRAP_ADMIN_USERNAME": "admin", "KC_BOOTSTRAP_ADMIN_PASSWORD": "admin"}},
}


def job(env: dict) -> dict:
    services = {"postgres": {
        "image": f"postgres:{env['postgres']}",
        "env": {"POSTGRES_PASSWORD": "test"},
        "ports": ["5432:5432"],
        "options": "--health-cmd pg_isready --health-interval 2s --health-retries 30",
    }}
    variables = {"DATABASE_URL": "postgresql://postgres:test@localhost:5432/postgres",
                 "EXPECTED_PG_MAJOR": env["postgres"]}
    if env["proxy"] != "none":
        services["proxy"] = SERVICES[env["proxy"]]
        variables["HTTPS_PROXY"] = "http://localhost:3128"
        variables["NO_PROXY"] = "localhost,127.0.0.1"
    if env["sso"] == "keycloak":
        services["keycloak"] = SERVICES["keycloak"]
        variables["SSO_METADATA_URL"] = "http://localhost:8081/realms/master/protocol/saml/descriptor"
    if env["ca"] == "corporate":
        variables["CA_BUNDLE"] = "${{ github.workspace }}/matrix/fixtures/corp-ca.pem"
    return {
        "name": env["name"],
        "runs-on": "ubuntu-24.04",
        "services": services,
        "env": variables,
        "steps": [
            {"uses": "actions/checkout@v4"},
            {"uses": "actions/setup-python@v5", "with": {"python-version": "3.12"}},
            {"run": "pip install -r checks/requirements.txt"},
            {"run": f"pytest checks -v --junitxml=results/{env['name']}.xml"},
            {"if": "always()", "uses": "actions/upload-artifact@v4",
             "with": {"name": f"result-{env['name']}", "path": f"results/{env['name']}.xml"}},
        ],
    }


def main() -> None:
    envs = yaml.safe_load((ROOT / "matrix/environments.yaml").read_text())["environments"]
    names = [e["name"] for e in envs]
    if len(names) != len(set(names)):
        raise SystemExit("environment names must be unique")
    workflow = {
        "name": "environment-matrix",
        "on": {"push": {"branches": ["main"]}, "pull_request": {}, "schedule": [{"cron": "0 2 * * 1"}]},
        "jobs": {e["name"]: job(e) for e in envs} | {
            "report": {
                "needs": names, "if": "always()", "runs-on": "ubuntu-24.04",
                "steps": [
                    {"uses": "actions/checkout@v4"},
                    {"uses": "actions/download-artifact@v4", "with": {"path": "results", "merge-multiple": True}},
                    {"run": "pip install pyyaml && python matrix/report.py results >> $GITHUB_STEP_SUMMARY"},
                ],
            }
        },
    }
    out = ROOT / ".github/workflows/matrix.yml"
    out.write_text("# GENERATED by matrix/generate.py. Edit matrix/environments.yaml instead.\n"
                   + yaml.safe_dump(workflow, sort_keys=False, width=120))
    print(f"wrote {out.relative_to(ROOT)} with {len(envs)} environments")


if __name__ == "__main__":
    main()
